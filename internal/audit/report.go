package audit

import (
	"cmp"
	"fmt"
	"io"
	"slices"
	"strings"

	"github.com/YakDriver/hedgetrimmer/internal/config"
)

type rankInfo struct{ label, effort, likelihood string }

var rankInfos = map[string]rankInfo{
	config.RankBot:       {"Automation/bot, no open PR", "trivial (bot, job done)", "very high"},
	config.RankInDefault: {"Content already in `%s` (patch-equivalent), no open PR", "trivial (content preserved)", "very high"},
	config.RankNoOwner:   {"No current owner (former or external), no open PR", "low–medium (skim commits)", "high"},
	config.RankStale:     {"Current maintainer, stale >%dd, no open PR", "medium (confirm with owner)", "medium"},
	config.RankRecent:    {"Current maintainer, recent ≤%dd, no open PR", "medium", "low"},
	config.RankOpenPR:    {"Active: open PR", "n/a", "keep"},
}

func rankLabel(cfg *config.Config, base, id string) string {
	l := rankInfos[id].label
	switch id {
	case config.RankInDefault:
		return fmt.Sprintf(l, base)
	case config.RankStale, config.RankRecent:
		return fmt.Sprintf(l, cfg.StaleDays)
	}
	return l
}

// actionable buckets get checkboxes so the worksheet can track deletions.
var actionable = []string{config.RankBot, config.RankInDefault, config.RankNoOwner, config.RankStale, config.RankRecent}

// WriteMarkdown renders res as a GitHub-issue worksheet, most deletable first.
func WriteMarkdown(w io.Writer, cfg *config.Config, res *Result) error {
	var sb strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&sb, format, a...) }

	counts := map[string]int{}
	for _, b := range res.Branches {
		counts[b.Bucket]++
	}

	if cfg.Header != "" {
		p("%s\n\n", strings.TrimSpace(cfg.Header))
	}
	p("Audit of the **%d** branches in `%s` (excluding `%s`), ordered so branches that are quick to check and likely deletable come first. Generated by [hedgetrimmer](https://github.com/YakDriver/hedgetrimmer); it never deletes anything.\n\n",
		len(res.Branches), res.Repo, res.Base)

	p("## Ranking\n\n")
	p("| Rank | Bucket | Count | Effort to validate | Likelihood deletable |\n")
	p("|---|---|--:|---|---|\n")
	for _, id := range config.Ranks {
		ri := rankInfos[id]
		p("| %s | %s | %d | %s | %s |\n", id, rankLabel(cfg, res.Base, id), counts[id], ri.effort, ri.likelihood)
	}
	for _, pr := range cfg.Protect {
		p("| %s | %s | %d | n/a | n/a |\n", pr.Name, pr.Title, counts[pr.Name])
	}
	p("\n_Owner is the most current of the PR author and the tip commit's author, checked against the maintainer roster. Best effort._\n")

	section := func(id, title string) {
		group := slices.DeleteFunc(slices.Clone(res.Branches), func(b Branch) bool { return b.Bucket != id })
		if len(group) == 0 {
			return
		}
		// Oldest first; name breaks ties so output is stable.
		slices.SortFunc(group, func(a, b Branch) int {
			return cmp.Or(a.Date.Compare(b.Date), strings.Compare(a.Name, b.Name))
		})
		heading := fmt.Sprintf("%s: %s (%d)", id, title, len(group))
		collapsed := slices.Contains(cfg.Collapse, id)
		if collapsed {
			p("\n<details><summary>%s</summary>\n\n", heading)
		} else {
			p("\n## %s\n\n", heading)
		}
		box := slices.Contains(actionable, id)
		for _, b := range group {
			p("%s\n", line(b, res.Base, box))
		}
		if collapsed {
			p("\n</details>\n")
		}
	}
	for _, id := range config.Ranks {
		section(id, rankLabel(cfg, res.Base, id))
	}
	for _, pr := range cfg.Protect {
		section(pr.Name, pr.Title)
	}

	_, err := io.WriteString(w, sb.String())
	return err
}

func line(b Branch, base string, checkbox bool) string {
	mark := "- "
	if checkbox {
		mark = "- [ ] "
	}
	pr := "no PR"
	if b.PR != nil {
		pr = fmt.Sprintf("#%d", b.PR.Number)
		if b.PR.State != "OPEN" {
			pr += " (" + strings.ToLower(b.PR.State) + ")"
		}
	}
	s := fmt.Sprintf("%s`%s`: %s (%dd), %s, owner `%s` (%s), tip `%s`",
		mark, b.Name, b.Date.Format("2006-01-02"), b.Age, pr, b.Owner, b.Status, b.SHA)
	if b.InBase {
		s += fmt.Sprintf(" **[content in `%s`]**", base)
	}
	return s
}
